-- ============================================================
-- 宠物经验持久化：pets 表补 exp 列
-- 幂等，可重复执行；建议在 Supabase SQL Editor 执行一次，再部署前端代码。
--
-- 背景（Bug 修复）：
--   之前只把 level 同步云端，exp（当前等级已攒的经验）没存。
--   表现：刷新页面等级还在，但经验条清零、从 0 重新攒。
--   补列后：等级 + 经验条一起存，刷新后进度条接着走。
--
-- 兼容：前端已做缺列降级（查不到 exp 列时自动退回旧列集），
--       所以「先部署代码、后跑本迁移」也不会崩，只是经验条暂不持久化。
-- ============================================================

alter table public.pets
  add column if not exists exp integer not null default 0;

comment on column public.pets.exp is '当前等级已攒经验（升级时扣除本级所需，余下留存；满级时恒等于本级所需）';
